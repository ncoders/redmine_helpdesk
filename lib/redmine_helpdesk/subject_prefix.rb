module RedmineHelpdesk
  # Issue references in mail subjects carrying a configurable prefix,
  # e.g. "[ACME #1234]". Redmine accepts any "[... #1234]" in the subject
  # as a reply to issue #1234, so references added by other ticket
  # systems ("[Foo #1234]") end up as notes on unrelated issues.
  # See https://www.redmine.org/issues/18668
  #
  # Without a configured prefix everything behaves like before.
  module SubjectPrefix
    def self.settings
      Setting.plugin_redmine_helpdesk || {}
    end

    # The configured prefix, without characters that would break the
    # "[PREFIX ... #id]" format
    def self.prefix
      settings['subject_prefix'].to_s.gsub(/[\[\]#]/, '').squish
    end

    def self.enabled?
      prefix.present?
    end

    # Only accept In-Reply-To/References Message-IDs generated by this
    # Redmine (on by default)
    def self.own_host_only?
      settings['own_host_only'].to_s != '0'
    end

    # Host part of the Message-IDs generated by Mailer.token_for and
    # HelpdeskMailer.token_for (same computation)
    def self.own_host
      host = Setting.mail_from.to_s.strip.gsub(%r{^.*@|>}, '')
      host = "#{::Socket.gethostname}.redmine" if host.empty?
      host
    end

    # Subject tag of mails sent to the supportclient
    def self.customer_tag(issue)
      if enabled?
        "[#{prefix} ##{issue.id}]"
      else
        "[#{issue.project.name} - ##{issue.id}]"
      end
    end

    # Subject tag of regular Redmine notifications
    def self.internal_tag(issue)
      if enabled?
        "[#{prefix} #{issue.project.name} - #{issue.tracker.name} ##{issue.id}]"
      else
        core_tag(issue)
      end
    end

    # Subject tag as built by Mailer#issue_add
    def self.core_tag(issue)
      "[#{issue.project.name} - #{issue.tracker.name} ##{issue.id}]"
    end

    # Matches "[PREFIX #id]" and "[PREFIX anything #id]"
    def self.issue_reply_subject_re
      %r{\[#{Regexp.escape(prefix)}(?:\s+[^\]]*)?\s+#(\d+)\]}i
    end

    # Like MailHandler::MESSAGE_ID_RE, optionally restricted to own_host
    def self.message_id_re
      host = own_host_only? ? "(?i:#{Regexp.escape(own_host)})" : '[^>]+'
      %r{\A<?redmine\.([a-z0-9_]+)\-(\d+)\.\d+(\.[a-f0-9]+)?@#{host}>?\z}
    end
  end
end
